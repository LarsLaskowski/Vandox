    private static readonly Dictionary<string, int> _tcp = Create(false);
    private static readonly Dictionary<string, int> _udp = Create(true);

    #endregion // Fields

    #region Methods

    /// <summary>
    /// Looks up the port of a service name.
    /// </summary>
    /// <param name="name">The service name</param>
    /// <param name="udp"><c>true</c> for the udp protocol, <c>false</c> for tcp</param>
    /// <param name="port">The port when found</param>
    /// <returns><c>true</c> when the name is known for the protocol</returns>
    internal static bool TryGetPort(string name, bool udp, out int port)
    {
        return (udp ? _udp : _tcp).TryGetValue(name, out port);
    }

    /// <summary>
    /// Builds the table of one protocol from the entries.
    /// </summary>
    /// <param name="udp"><c>true</c> for udp, <c>false</c> for tcp</param>
    /// <returns>The ports by name</returns>
    private static Dictionary<string, int> Create(bool udp)
    {
        var kind = udp ? 'u' : 't';
        var table = new Dictionary<string, int>(StringComparer.Ordinal);

        foreach (var entry in _entries)
        {
            var parts = entry.Split(' ');

            if (parts[2].Contains(kind, StringComparison.Ordinal))
            {
                table.TryAdd(parts[0], int.Parse(parts[1], System.Globalization.CultureInfo.InvariantCulture));
            }
        }

        return table;
    }

    #endregion // Methods
